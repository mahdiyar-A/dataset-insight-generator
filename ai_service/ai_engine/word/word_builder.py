"""
Word (.docx) Report Builder  —  DIG AI Engine

Converts an LLMReport into a professional .docx file using python-docx.
Called by the pipeline when the user's customization includes outputFormat.word = true.

Structure mirrors the PDF report:
  Cover page    → title, date, domain
  Executive summary
  Insights      → one section per insight (rank 1..N)
  Data quality  → methodology section
  Conclusion

Returns: bytes  (the .docx file contents, ready for base64 encoding)
"""

import io
from datetime import datetime
from typing import Optional

try:
    from docx import Document
    from docx.shared import Pt, RGBColor, Inches, Cm
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml.ns import qn
    from docx.oxml import OxmlElement
    DOCX_AVAILABLE = True
except ImportError:
    DOCX_AVAILABLE = False


# ── Brand colours (matching PDF palette) ─────────────────────────────────────
COLOR_PRIMARY   = RGBColor(0x1A, 0x1A, 0x2E) if DOCX_AVAILABLE else None  # deep navy
COLOR_ACCENT    = RGBColor(0x4F, 0x46, 0xE5) if DOCX_AVAILABLE else None  # indigo
COLOR_BODY      = RGBColor(0x1F, 0x2D, 0x3D) if DOCX_AVAILABLE else None  # dark slate
COLOR_MUTED     = RGBColor(0x64, 0x74, 0x8B) if DOCX_AVAILABLE else None  # slate-500
COLOR_WHITE     = RGBColor(0xFF, 0xFF, 0xFF) if DOCX_AVAILABLE else None


def _set_heading_style(para, level: int = 1):
    """Apply heading font styling directly (avoids relying on template styles)."""
    run = para.runs[0] if para.runs else para.add_run()
    run.bold = True
    if level == 1:
        run.font.size = Pt(18)
        run.font.color.rgb = COLOR_PRIMARY
    elif level == 2:
        run.font.size = Pt(14)
        run.font.color.rgb = COLOR_ACCENT
    else:
        run.font.size = Pt(12)
        run.font.color.rgb = COLOR_BODY


def _add_heading(doc: "Document", text: str, level: int = 1):
    para = doc.add_paragraph()
    para.paragraph_format.space_before = Pt(16 if level == 1 else 10)
    para.paragraph_format.space_after  = Pt(6)
    run = para.add_run(text)
    run.bold = True
    if level == 1:
        run.font.size = Pt(18)
        run.font.color.rgb = COLOR_PRIMARY
    elif level == 2:
        run.font.size = Pt(14)
        run.font.color.rgb = COLOR_ACCENT
    else:
        run.font.size = Pt(12)
        run.font.color.rgb = COLOR_BODY
    return para


def _add_body(doc: "Document", text: str, italic: bool = False):
    para = doc.add_paragraph()
    para.paragraph_format.space_after = Pt(6)
    run = para.add_run(text)
    run.font.size = Pt(11)
    run.italic = italic
    run.font.color.rgb = COLOR_BODY
    return para


def _add_horizontal_rule(doc: "Document"):
    """Add a thin grey horizontal line as a paragraph border."""
    para = doc.add_paragraph()
    para.paragraph_format.space_before = Pt(4)
    para.paragraph_format.space_after  = Pt(4)
    pPr = para._p.get_or_add_pPr()
    pBdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"),   "single")
    bottom.set(qn("w:sz"),    "6")
    bottom.set(qn("w:space"), "1")
    bottom.set(qn("w:color"), "CBD5E1")   # slate-300
    pBdr.append(bottom)
    pPr.append(pBdr)


def build_word_doc(report, file_name: str = "dataset.csv", domain: str = "general") -> bytes:
    """
    Build a .docx Word report from an LLMReport object.

    Args:
        report: LLMReport dataclass (from gemini_client)
        file_name: original uploaded filename (shown on cover)
        domain: domain string (finance, hr, etc.)

    Returns:
        bytes — the .docx file contents
    """
    if not DOCX_AVAILABLE:
        raise ImportError(
            "python-docx is not installed. Run: pip install python-docx"
        )

    doc = Document()

    # ── Page margins ──────────────────────────────────────────────────────────
    for section in doc.sections:
        section.top_margin    = Inches(1.0)
        section.bottom_margin = Inches(1.0)
        section.left_margin   = Inches(1.2)
        section.right_margin  = Inches(1.2)

    # ── Cover / title block ───────────────────────────────────────────────────
    title_para = doc.add_paragraph()
    title_para.alignment = WD_ALIGN_PARAGRAPH.LEFT
    title_para.paragraph_format.space_before = Pt(0)
    title_para.paragraph_format.space_after  = Pt(4)
    title_run = title_para.add_run(report.reportTitle or "Dataset Insight Report")
    title_run.bold = True
    title_run.font.size = Pt(24)
    title_run.font.color.rgb = COLOR_PRIMARY

    meta_para = doc.add_paragraph()
    meta_para.paragraph_format.space_after = Pt(0)
    meta_run = meta_para.add_run(
        f"Generated by DIG  ·  {domain.title()} Analysis  ·  "
        f"{datetime.utcnow().strftime('%B %d, %Y')}"
    )
    meta_run.font.size = Pt(10)
    meta_run.font.color.rgb = COLOR_MUTED
    meta_run.italic = True

    file_para = doc.add_paragraph()
    file_para.paragraph_format.space_after = Pt(12)
    file_run = file_para.add_run(f"Source file: {file_name}")
    file_run.font.size = Pt(10)
    file_run.font.color.rgb = COLOR_MUTED

    _add_horizontal_rule(doc)

    # ── Introduction ──────────────────────────────────────────────────────────
    if report.introduction:
        _add_body(doc, report.introduction, italic=True)
        _add_horizontal_rule(doc)

    # ── Executive Summary ─────────────────────────────────────────────────────
    _add_heading(doc, "Executive Summary", level=1)
    _add_body(doc, report.executiveSummary or "See insights below.")

    # ── Insights ──────────────────────────────────────────────────────────────
    _add_heading(doc, "Key Insights", level=1)

    for insight in (report.insights or []):
        rank  = insight.get("rank", "—")
        title = insight.get("title", f"Insight {rank}")
        body  = insight.get("body", "")

        insight_heading = doc.add_paragraph()
        insight_heading.paragraph_format.space_before = Pt(10)
        insight_heading.paragraph_format.space_after  = Pt(4)
        h_run = insight_heading.add_run(f"{rank}.  {title}")
        h_run.bold = True
        h_run.font.size = Pt(13)
        h_run.font.color.rgb = COLOR_ACCENT

        if body:
            _add_body(doc, body)

    # ── Data Quality & Methodology ────────────────────────────────────────────
    if report.dataQualitySection:
        _add_horizontal_rule(doc)
        _add_heading(doc, "Data Quality & Methodology", level=1)
        _add_body(doc, report.dataQualitySection)

    # ── Conclusion ────────────────────────────────────────────────────────────
    if report.conclusion:
        _add_horizontal_rule(doc)
        _add_heading(doc, "Conclusion", level=1)
        _add_body(doc, report.conclusion)

    # ── Confidence note ───────────────────────────────────────────────────────
    if report.confidenceNote:
        _add_horizontal_rule(doc)
        note_para = doc.add_paragraph()
        note_para.paragraph_format.space_before = Pt(6)
        note_run = note_para.add_run(f"Analyst note: {report.confidenceNote}")
        note_run.font.size = Pt(10)
        note_run.italic = True
        note_run.font.color.rgb = COLOR_MUTED

    # ── Footer stamp ──────────────────────────────────────────────────────────
    _add_horizontal_rule(doc)
    footer_para = doc.add_paragraph()
    footer_para.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    footer_run = footer_para.add_run(
        f"DIG — Dataset Insight Generator  ·  {datetime.utcnow().strftime('%Y')}"
    )
    footer_run.font.size = Pt(9)
    footer_run.font.color.rgb = COLOR_MUTED

    # ── Serialize to bytes ────────────────────────────────────────────────────
    buf = io.BytesIO()
    doc.save(buf)
    buf.seek(0)
    return buf.read()
