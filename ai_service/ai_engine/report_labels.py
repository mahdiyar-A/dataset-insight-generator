def labels_for(language: str) -> Dict[str, str]:
    """Labels for a report language, falling back to English per key."""
    lang = (language or "en").lower()[:2]
    chosen = LABELS.get(lang, {})
    return {key: chosen.get(key, value) for key, value in LABELS["en"].items()}


def left_out_line(detail: Dict[str, Any], language: str = "en") -> str:
    """One sentence naming what a report does not cover, or "" if it covers it all."""
    others = detail.get("otherSheets") or detail.get("otherTables") or []
    read = detail.get("sheet") or detail.get("table")
    if not others or not read:
        return ""
    names = ", ".join(others[:5]) + (", ..." if len(others) > 5 else "")
    return labels_for(language)["not_read"].format(read=read, names=names)


def basis_line(insight: Dict[str, Any], labels: Dict[str, str], rtl: bool = False) -> str:
    """'Based on: ...' for an insight, from the lines evidence.py wrote, or ""."""
    lines = [str(x) for x in (insight.get("basedOn") or []) if x]
    if not lines:
        return ""
    return f"{labels['based_on']}: " + ("؛ " if rtl else "; ").join(lines)


def described_line(description: str, by_user: bool, language: str = "en") -> str:
    """
    One sentence saying what the data was taken to be, or "" when there is
    nothing to say. A reader should be able to see what reading the report
    rests on, most of all when it was the reader's own.
    """
    description = (description or "").strip().rstrip(".")
    if not description:
        return ""
    labels = labels_for(language)
    if by_user:
        return labels["described_by_you"].format(description=description)
    # The model's own sentence is in English. In a report written in another
    # language it would be one stray English line, and the domain is on the
    # cover either way.
    if (language or "en").lower()[:2] != "en":
        return ""
    return READ_AS.format(description=description)


def is_rtl(language: str) -> bool:
    return (language or "").lower()[:2] in RTL_LANGUAGES


def confidence_word(score: int, labels: Dict[str, str]) -> str:
    return labels["high"] if score >= 8 else labels["medium"] if score >= 5 else labels["low"]
