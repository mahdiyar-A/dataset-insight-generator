def labels_for(language: str) -> Dict[str, str]:
    """Labels for a report language, falling back to English per key."""
    lang = (language or "en").lower()[:2]
    chosen = LABELS.get(lang, {})
    return {key: chosen.get(key, value) for key, value in LABELS["en"].items()}


def left_out_line(detail: Dict[str, Any], language: str = "en") -> str:
    """One sentence naming what a report does not cover, or "" if it covers it all."""
    others = detail.get("otherSheets") or detail.get("otherTables") or []
    read = detail.get("sheet") or detail.get("table")
    if not others or not read:
        return ""
    names = ", ".join(others[:5]) + (", ..." if len(others) > 5 else "")
    return labels_for(language)["not_read"].format(read=read, names=names)


def is_rtl(language: str) -> bool:
    return (language or "").lower()[:2] in RTL_LANGUAGES


def confidence_word(score: int, labels: Dict[str, str]) -> str:
    return labels["high"] if score >= 8 else labels["medium"] if score >= 5 else labels["low"]
